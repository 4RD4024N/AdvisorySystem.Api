SELECT 
    cc.Name as [Kategori],
    COUNT(c.Id) as [Toplam],
    SUM(CASE WHEN c.Description IS NOT NULL AND c.Description != '' THEN 1 ELSE 0 END) as [Açýklamalý],
    SUM(CASE WHEN c.Description IS NULL OR c.Description = '' THEN 1 ELSE 0 END) as [Açýklamasýz]
FROM CourseCategories cc
LEFT JOIN Courses c ON cc.Id = c.CategoryId
GROUP BY cc.Name, cc.DisplayOrder
ORDER BY cc.DisplayOrder;

