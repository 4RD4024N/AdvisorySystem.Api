SELECT 
    ISNULL(CAST(Semester AS VARCHAR), 'Yarýyýlsýz') as [Yarýyýl],
    COUNT(*) as [Toplam],
    SUM(CASE WHEN Description IS NOT NULL AND Description != '' THEN 1 ELSE 0 END) as [Açýklamalý],
    SUM(CASE WHEN Description IS NULL OR Description = '' THEN 1 ELSE 0 END) as [Açýklamasýz]
FROM Courses
GROUP BY Semester
ORDER BY Semester;

